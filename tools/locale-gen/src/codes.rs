use std::fmt::Write as _;

use crate::parse::FtlEntry;

pub const RUST_GENERATED_HEADER: &str = "// Generated by tools/locale-gen. Do not edit by hand.\n";
pub const TS_GENERATED_HEADER: &str = "// Generated by tools/locale-gen. Do not edit by hand.\n";

#[must_use]
pub fn camel_case(id: &str) -> String {
    let mut out = String::new();
    let mut upper_next = true;
    for c in id.chars() {
        if c == '-' {
            upper_next = true;
            continue;
        }
        if c.is_ascii_digit() {
            out.push(c);
            upper_next = false;
            continue;
        }
        if upper_next {
            out.push(c.to_ascii_uppercase());
        } else {
            out.push(c);
        }
        upper_next = false;
    }
    out
}

fn w(out: &mut String, text: &str) {
    let _result = writeln!(out, "{text}");
}

fn rust_enum_header(entries: &[FtlEntry], out: &mut String) {
    w(out, "// Source: locales/en.ftl");
    w(out, "use serde;");
    w(
        out,
        "#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash, PartialOrd, Ord, serde::Serialize)]",
    );
    w(out, "#[serde(rename_all = \"kebab-case\")]");
    w(out, "pub enum MessageCode {");
    for entry in entries {
        w(out, &format!("    {},", camel_case(&entry.id)));
    }
    w(out, "}\n");
}

fn rust_from_str_impl(out: &mut String) {
    w(out, "impl std::str::FromStr for MessageCode {");
    w(out, "    type Err = String;");
    w(
        out,
        "\n    fn from_str(text: &str) -> Result<Self, Self::Err> {",
    );
    w(
        out,
        "        Self::from_code(text).ok_or_else(|| format!(\"unknown message code {text:?}\"))",
    );
    w(out, "    }");
    w(out, "}\n");
}

fn rust_as_str(_entries: &[FtlEntry], out: &mut String) {
    w(out, "    #[must_use]");
    w(out, "    pub fn as_str(self) -> &'static str {");
    w(
        out,
        "        match TABLE.iter().find(|row| row.0 == self) {",
    );
    w(out, "            Some(row) => row.1,");
    w(out, "            None => \"unknown\",");
    w(out, "        }");
    w(out, "    }");
}

fn rust_helpers(entries: &[FtlEntry], out: &mut String) {
    w(out, "const TABLE: &[(MessageCode, &str)] = &[");
    for entry in entries {
        w(
            out,
            &format!(
                "    (MessageCode::{}, {:?}),",
                camel_case(&entry.id),
                entry.id
            ),
        );
    }
    w(out, "];\n");
}

fn rust_from_code(_entries: &[FtlEntry], out: &mut String) {
    w(out, "    #[must_use]");
    w(out, "    pub fn from_code(text: &str) -> Option<Self> {");
    w(
        out,
        "        TABLE.iter().find(|row| row.1 == text).map(|row| row.0)",
    );
    w(out, "    }");
}

fn rust_all(_entries: &[FtlEntry], out: &mut String) {
    w(out, "    #[must_use]");
    w(out, "    pub fn all() -> Vec<Self> {");
    w(out, "        TABLE.iter().map(|row| row.0).collect()");
    w(out, "    }\n}\n");
    w(
        out,
        "impl crate::catalog::MessageCodeLike for MessageCode {\n    fn as_str(&self) -> &str {\n        MessageCode::as_str(*self)\n    }\n}\n",
    );
}

pub fn rust_codes(entries: &[FtlEntry]) -> Result<String, String> {
    let code = rust_codes_raw(entries);
    format_rust(&code).map(|formatted| RUST_GENERATED_HEADER.to_owned() + &formatted)
}

fn rust_codes_raw(entries: &[FtlEntry]) -> String {
    let mut out = String::from(RUST_GENERATED_HEADER);
    rust_enum_header(entries, &mut out);
    rust_from_str_impl(&mut out);
    rust_helpers(entries, &mut out);
    w(&mut out, "impl MessageCode {");
    rust_as_str(entries, &mut out);
    w(&mut out, "}\n");
    w(&mut out, "impl MessageCode {");
    rust_from_code(entries, &mut out);
    rust_all(entries, &mut out);
    out
}

fn format_rust(code: &str) -> Result<String, String> {
    use std::io::Write as _;
    use std::process::Stdio;
    let body = code.strip_prefix(RUST_GENERATED_HEADER).unwrap_or(code);
    let mut child = std::process::Command::new("rustfmt")
        .arg("--edition")
        .arg("2024")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| format!("spawn rustfmt failed: {e}"))?;
    if let Some(stdin) = child.stdin.as_mut() {
        let _result = stdin.write_all(body.as_bytes());
    }
    let out = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt wait failed: {e}"))?;
    if !out.status.success() {
        return Err("rustfmt exited with a failure".to_owned());
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

fn ts_union(entries: &[FtlEntry], out: &mut String) {
    w(out, "// Source: locales/en.ftl");
    w(out, "export type MessageCode =");
    for (i, entry) in entries.iter().enumerate() {
        let tail = if i.checked_add(1) == Some(entries.len()) {
            ";"
        } else {
            " |"
        };
        w(out, &format!("  {:?}{}", entry.id, tail));
    }
    w(out, "");
}

#[must_use]
pub fn ts_codes(entries: &[FtlEntry]) -> String {
    let mut out = String::from(TS_GENERATED_HEADER);
    ts_union(entries, &mut out);
    w(
        &mut out,
        "export const ALL_MESSAGE_CODES: MessageCode[] = [",
    );
    for entry in entries {
        w(&mut out, &format!("  {:?},", entry.id));
    }
    w(&mut out, "];");
    out
}

#[must_use]
pub fn ts_locales(en: &str, zh: &str) -> String {
    let mut out = String::from(TS_GENERATED_HEADER);
    w(&mut out, "// Source: locales/en.ftl and locales/zh-TW.ftl");
    w(
        &mut out,
        &format!("export const EN_FTL_SOURCE = {}", escape_ts_string(en)),
    );
    w(
        &mut out,
        &format!("export const ZH_TW_FTL_SOURCE = {}", escape_ts_string(zh)),
    );
    out
}

#[must_use]
pub fn escape_ts_string(text: &str) -> String {
    let mut out = String::from("\"");
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c < ' ' => {
                let _result = write!(out, "\\u{:04x}", u32::from(c));
            }
            c if c.is_ascii() => out.push(c),
            c => push_escaped_codepoint(&mut out, u32::from(c)),
        }
    }
    out.push('"');
    out
}

fn push_escaped_codepoint(out: &mut String, cp: u32) {
    if cp <= 0xFFFF {
        let _result = write!(out, "\\u{cp:04x}");
        return;
    }
    let biased = cp.saturating_sub(0x1_0000);
    let high = (biased >> 10).wrapping_add(0xD800);
    let low = (biased & 0x3FF).wrapping_add(0xDC00);
    let _result = write!(out, "\\u{high:04x}\\u{low:04x}");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::parse_ftl;

    fn sample() -> Vec<FtlEntry> {
        parse_ftl("server-startup-listening = v { $version }\nui-shell-2 = x\n")
    }

    #[test]
    fn test_camel_case_maps_kebab_ids_to_identifiers() {
        assert_eq!(
            camel_case("server-startup-listening"),
            "ServerStartupListening"
        );
        assert_eq!(camel_case("ui-shell-2"), "UiShell2");
        assert_eq!(camel_case("a"), "A");
    }

    #[test]
    fn test_rust_codes_lists_every_entry_in_all_helpers() {
        let text = rust_codes(&sample()).expect("fixture codes format");
        assert!(text.starts_with(RUST_GENERATED_HEADER));
        assert!(text.contains("ServerStartupListening"));
        assert!(text.contains("\"server-startup-listening\""));
        assert!(text.contains("UiShell2"));
        assert!(text.contains("pub fn all()"));
        assert!(text.contains("TABLE.iter().map(|row| row.0).collect()"));
    }

    #[test]
    fn test_ts_codes_union_covers_every_entry() {
        let text = ts_codes(&sample());
        assert!(text.starts_with(TS_GENERATED_HEADER));
        assert!(text.contains("\"server-startup-listening\""));
        assert!(text.contains("\"ui-shell-2\""));
        assert!(text.contains("ALL_MESSAGE_CODES"));
    }

    #[test]
    fn test_ts_locales_escapes_cjk_and_quotes() {
        let got = ts_locales("a = Say \"hi\"\n", "a = \u{8aaa}\u{8aa1}\n");
        assert!(
            got.contains("export const EN_FTL_SOURCE = \"a = Say \\\"hi\\\"\\n\""),
            "{got}"
        );
        assert!(got.contains("\\u8aaa\\u8aa1"), "{got}");
        assert!(got.is_ascii(), "generated locales must be ascii");
    }

    #[test]
    fn test_ts_locales_escapes_astral_codepoints_as_surrogate_pairs() {
        let got = ts_locales("a = x\n", "a = \u{20000}\n");
        assert!(got.contains("\\ud840\\udc00"), "{got}");
        assert!(got.is_ascii(), "generated locales must be ascii");
    }
}
